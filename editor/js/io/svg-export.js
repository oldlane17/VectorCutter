/**
 * VectorCutter - Pure SVG Exporter
 * Exports clean, laser-ready SVG files in physical millimetres (mm).
 * Preserves generator params and 3D settings via data-vc-* attributes (§3 & §7.9).
 */

import { matrixToSVGTransform } from '../model/matrix.js';
import { getElementLocalBounds, getTransformedCorners } from '../model/bounds.js';
import { generateStarVertices, generatePolygonVertices } from '../model/generators.js';

export function exportSVGString(store, options = {}) {
    const doc = store.doc;
    const elements = options.selectionOnly ? store.getSelectedElements() : store.getAllElements();

    if (elements.length === 0) {
        return '<svg xmlns="http://www.w3.org/2000/svg" width="100mm" height="100mm" viewBox="0 0 100 100"></svg>';
    }

    // Compute tight, rotation-aware bounding box in mm
    let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
    let maxStrokeW = 0.1;

    elements.forEach(el => {
        const box = getElementLocalBounds(el);
        const corners = getTransformedCorners(box, el.transform || [1, 0, 0, 1, 0, 0]);
        corners.forEach(c => {
            minX = Math.min(minX, c.x);
            minY = Math.min(minY, c.y);
            maxX = Math.max(maxX, c.x);
            maxY = Math.max(maxY, c.y);
        });
        const sw = parseFloat(el.style?.strokeWidth || 0.1);
        if (sw > maxStrokeW) maxStrokeW = sw;
    });

    // Content-tight margin: only stroke half-width so cuts are exact to line size (§Issue 7)
    const extraMargin = options.margin !== undefined ? options.margin : 0;
    const margin = (maxStrokeW / 2) + extraMargin;

    const x = minX - margin;
    const y = minY - margin;
    const w = (maxX - minX) + margin * 2;
    const h = (maxY - minY) + margin * 2;

    let svg = `<?xml version="1.0" encoding="UTF-8"?>\n`;
    svg += `<svg xmlns="http://www.w3.org/2000/svg" width="${w.toFixed(3)}mm" height="${h.toFixed(3)}mm" viewBox="${x.toFixed(4)} ${y.toFixed(4)} ${w.toFixed(4)} ${h.toFixed(4)}">\n`;
    svg += `  <!-- Generated by VectorCutter (https://vectorcutter.oldlane17.com) -->\n`;

    elements.forEach(el => {
        const tStr = matrixToSVGTransform(el.transform);
        const transformAttr = tStr ? ` transform="${tStr}"` : '';
        const idAttr = ` id="${el.id}"`;
        const nameAttr = el.name ? ` data-vc-name="${encodeURIComponent(el.name)}"` : '';
        const paramsAttr = el.params ? ` data-vc-params="${encodeURIComponent(JSON.stringify(el.params))}"` : '';
        const threeDAttr = el.threeD ? ` data-vc-3d="${encodeURIComponent(JSON.stringify(el.threeD))}"` : '';
        const rotCenterAttr = el.rotationCenter ? ` data-vc-rotcenter="${encodeURIComponent(JSON.stringify(el.rotationCenter))}"` : '';

        let fill = el.style?.fill || 'none';
        let stroke = el.style?.stroke || '#000000';
        let strokeW = el.style?.strokeWidth || 0.5;

        if (el.laser?.op === 'cut') {
            fill = 'none';
            stroke = '#ff0000';
            strokeW = 0.1;
        } else if (el.laser?.op === 'score') {
            fill = 'none';
            stroke = '#0000ff';
            strokeW = 0.1;
        } else if (el.laser?.op === 'engrave') {
            stroke = 'none';
        }

        const g = el.geometry || {};
        const meta = `${idAttr}${nameAttr}${paramsAttr}${threeDAttr}${rotCenterAttr}${transformAttr}`;

        switch (el.type) {
            case 'rect':
                svg += `  <rect x="${g.x || 0}" y="${g.y || 0}" width="${g.width || 0}" height="${g.height || 0}" fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            case 'circle':
                svg += `  <circle cx="${g.cx || 0}" cy="${g.cy || 0}" r="${g.r || 0}" fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            case 'ellipse':
                svg += `  <ellipse cx="${g.cx || 0}" cy="${g.cy || 0}" rx="${g.rx || 0}" ry="${g.ry || 0}" fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            case 'polygon': {
                const verts = el.params ? generatePolygonVertices(el.params) : [];
                const ptsStr = verts.length > 0 ? verts.map(v => `${v.x.toFixed(2)},${v.y.toFixed(2)}`).join(' ') : (g.points || '');
                svg += `  <polygon points="${ptsStr}" fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            }
            case 'star': {
                const verts = el.params ? generateStarVertices(el.params) : [];
                const ptsStr = verts.length > 0 ? verts.map(v => `${v.x.toFixed(2)},${v.y.toFixed(2)}`).join(' ') : (g.points || '');
                svg += `  <polygon points="${ptsStr}" fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            }
            case 'line':
                svg += `  <line x1="${g.x1 || 0}" y1="${g.y1 || 0}" x2="${g.x2 || 0}" y2="${g.y2 || 0}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            case 'path':
                svg += `  <path d="${g.d || 'M 0 0'}" fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}/>\n`;
                break;
            case 'text': {
                if (g.isLaTeX) {
                    const renderedNode = document.querySelector(`#worldGroup [data-element-id="${el.id}"]`);
                    if (renderedNode && renderedNode.innerHTML) {
                        svg += `  <g fill="${fill}" stroke="${stroke}" stroke-width="${strokeW}"${meta}>${renderedNode.innerHTML}</g>\n`;
                        break;
                    }
                }
                svg += `  <text x="${g.x || 0}" y="${g.y || 0}" font-size="${g.fontSize || 14}" font-family="${g.fontFamily || 'Arial'}" fill="${fill}" stroke="${stroke}"${meta}>${g.text || ''}</text>\n`;
                break;
            }
        }
    });

    svg += `</svg>`;
    return svg;
}

export function downloadSVG(store, filename = 'vectorcutter.svg') {
    const svgStr = exportSVGString(store);
    const blob = new Blob([svgStr], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

export const generatePureSVG = exportSVGString;
